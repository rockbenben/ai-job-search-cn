_PUNCT_RE = re.compile(r"[\W_]+", re.UNICODE)


def normalize_key(s: str) -> str:
    return _PUNCT_RE.sub("", (s or "").lower())


def _fuzzy(a: str, b: str) -> bool:
    a, b = normalize_key(a), normalize_key(b)
    return bool(a) and bool(b) and (a in b or b in a)


def match_tracker(job: dict, url: str, tracker: list):
    """source URL 精确优先；退化 company+role 模糊（与 /job-html-report 同法）。

    **URL 比对前先剥协议**（`_cli.norm_url`）。同一个岗在台账里存 `https://`、
    在职位库里存 `http://` 是真实会发生的——智联的页面锚点给 `http://`，
    而早前入库的同一批岗是 `https://`。协议不同就认不出的后果是**把已投的岗
    重新摆回可投名单**，而重复投同一家正是求职最容易犯的错。
    这个仓库为「同一个岗有多把钥匙」付过四次学费（裸 URL vs `url#职位名`、
    同名材料目录、`validThrough` vs `deadline`、http vs https），这是第五处。
    """
    key = _cli.norm_url(url)
    for row in tracker:
        if key and _cli.norm_url(row.get("source")) == key:
            # URL 相同不足以断定是同一个职位：51job 实测同一详情 URL 下挂着两个不同
            # 职位（同公司的两个岗）。只比 URL 会让「投了甲」把同 URL 的乙也标成已投，
            # 乙随之从待投区消失。行里填了 role 就一并比对；没填（手工记的行常见）
            # 才退回只比 URL，避免因缺列而漏匹配。
            role = (row.get("role") or "").strip()
            if role and not _fuzzy(role, job.get("title", "")):
                continue
            return row
    for row in tracker:
        # 已经钉在**另一个** URL 上的投递记录行，记录的是另一次投递，不是这个岗。少了这条，
        # 同公司的新岗会被子串模糊匹配吃掉（「后端工程师」是「后端工程师（社招）」的
        # 子串），于是一个全新职位被标成已投、从待投区消失，ranked_urls 也随之为空。
        source = _cli.norm_url(row.get("source"))
        if key and source and source != key:
            continue
        # **脱敏串不构成公司身份。** 猎聘给猎头岗打的「某知名公司」「某上海互联网
        # 公司」是占位符不是名字：全库 2638 个岗里 1355 个脱敏，光「某知名公司」
        # 一个串就出现 158 次 —— 那是 158 家不同的用人方。拿它当键做模糊匹配，
        # 一条手工记的、没有链接的投递记录就能把库里 6 个岗一起标成已投
        # （实测活动用户），它们随即从可投名单里消失。
        # 上面那段说的「同一个岗有多把钥匙」是同一族的反面：这里是**一把钥匙
        # 开了六把锁**。没有链接又是脱敏公司时，宁可漏认，不可错认 ——
        # 漏认只是让他多看见一个已投的岗，错认是让六个没投的岗永远消失。
        if _cli.is_anonymous_employer(row.get("company", "")):
            continue
        if _fuzzy(row.get("company", ""), job.get("company", "")) and _fuzzy(
            row.get("role", ""), job.get("title", "")
        ):
            return row
    return None


_INTERVIEW_STATUSES = {"interview", "offer", "hired"}

#: 「拿到 offer 了」的状态值。**单独有它是因为 offer 要先于 interview 判**——
#: 这条规则本文件已经写过一次（逐岗那条：「拿到 offer 之后该做的是算可守区间、
#: 过背调红线、和别的 offer 比——那是 `/job-offer`，不是再练一轮面试题」），
#: 而流水线头顶那条从来不认它：`_INTERVIEW_STATUSES` 把 offer 一起收了，
#: 于是拿到 offer 的人在面板最显眼那一格读到的是「有面试了，去备面」。
#: 同一时刻终端说的是「有 1 个 offer 在手，跑 /job-offer」（2026-09-01 实测）。
#: 两个入口给相反的建议，而这一格是全流程最该谈钱的那一步。
_OFFER_STATUSES = {"offer"}


def derive_stage(job: dict, app, trow) -> str:
    """spec「职位 → 阶段派生」的优先级，从高到低。"""
    if trow is not None:
        return "applied"
    if job.get("status") == "expired":
        return "expired"
    if str(job.get("rank_verdict") or "").startswith("硬门 FAIL"):
        return "gate_fail"
    if app is not None and app.get("outreach"):
        return "materials"
    if job.get("status") == "ranked" and job.get("rank_score") is not None:
        if job.get("rank_verdict") in ("不建议", "跳过"):
            return "low"
        return "ranked"
    return "unranked"


def build_model(seen: dict, apps: list, tracker: list, profile_ok: bool,
                active_user: str = "", users=None, env_items=None) -> dict:
    """把 seen / 投递目录 / 台账 组装成一份内存模型。

    ⚠️ **这是测试夹具，不是生产路径。** 本文件没有 `main()`，`serve.py` 与
    `export_web_data.py` 都不导入它——面板看到的每一个数都由 `export_web_data`
    自己那条流水线算，`data.json` 也由它写。留着它是因为它是唯一能**在内存里**
    驱动「seen + 投递目录 + 台账 → 模型」的入口：`export_web_data` 只有一个读
    用户目录的 `main()`，8 个测试要为此各造一棵临时目录树才能替代它。

    ⚠️ **代价要说清：这里的计数与 `export_web_data` 各算一份，drift 是静默的。**
    2026-08-18 的审查就是这么发现 `ready_strong` 在这里读错了字段（读
    `rank_verdict`，而本函数造的 dict 里那一格叫 `verdict`）——恒为 0，测试全绿，
    而面板那份一直是对的。**在这里改任何计数，都要回头确认 `export_web_data`
    那份是不是也要改**；判词白名单已由
    `tests/test_ready_strong_counts_the_right_field` 钉住两边相等，其余口径没有。

    要撤掉这份重复，只有两条路，都不是小改动：让 `export_web_data` 暴露一个
    可注入的组装函数并让本函数退成它的薄壳；或者把那 8 处调用改成造临时目录树
    直接跑导出器。别第三种——尤其别「再加一份计数」。
    """
    # env_items 显式传入（默认 None = 不渲染环境面板），这样测试不必真跑 subprocess
    # 探测；main() 负责在真实运行时调用 probe_env() 传进来。
    env_items = env_items or []
    apps_by_url = dedup_apps_by_url(apps)
    jobs = []
    for key, entry in seen.items():
        url = entry.get("url") or (key if key.startswith("http") else "")
        app = apps_by_url.get(url)
        trow = match_tracker(entry, url, tracker)
        stage = derive_stage(entry, app, trow)
        interviewing = bool(
            (trow and (trow.get("status") or "").strip().lower() in _INTERVIEW_STATUSES)
            or (app and app["interview_preps"])
        )
        _resolved = resolve_score(entry, app)
        jobs.append({
            "url": url,
            # 用户在网页版点「不投」写回的状态。单页版原来完全没读它——
            # 于是同一份数据，网页版把它放进「不投的岗位」、单页版还当它是待办，
            # 「材料就绪」的数也就对不上。`derive_stage` 里没有 skipped 这一档
            # （那套阶段划分只表达流程推进，不表达用户的主动排除），所以单独带上。
            "skipped": entry.get("status") == "skipped",
            # seen_jobs 的键：CDP 渠道（BOSS/智联/前程）的条目**未必**有详情 URL——
            # 三家列表页大多有（BOSS `/job_detail/<id>.html`、智联 `/jobdetail/<id>.htm`、
            # 51job `jobs.51job.com/all/<id>.html`），但 51job 实测约 1/20 的卡片没有，
            # 所以 scrape.md 记的是 `<url_or_company_title_key>` 形式。「已发」勾选状态以
            # data-url 为 localStorage 键，若所有无 URL 的卡都渲染成空串，它们会共用
            # 同一个键——勾一张全部变已投，取消一张全部清空。
            "key": key,
            "title": entry.get("title") or "",
            "company": entry.get("company") or "",
            "portal": entry.get("portal") or "",
            # 深评优先——不能让面板一直显示 /job-rank 的粗筛分
            "score": _resolved[0],
            "verdict": _resolved[1],
            "evaluated": _resolved[2],
            "stage": stage,
            "interviewing": interviewing,
            "offer": bool(trow and (trow.get("status") or "").strip().lower()
                          in _OFFER_STATUSES),
            "app": app,
        })
    counts = {
        "scraped": len(jobs),
        # 与网页版**共用同一个实现**（就在本文件里，那边 import 过去）。
        # 曾经两边各写各的：这里数 `status == "ranked"`，那边数「有分数或已结案」，
        # 于是同一份数据两个面板显示 193 和 195。差额正是用户手动标「不投」的那 2 个
        # ——它们当然处理过了。而 `test_pipeline_counts.py` 里那个类叫
        # `CountsAgreeAcrossEntryPoints`，却只比了导出与盘上数据，从没比过这两个入口，
        # 名字承诺的比它做的多。同一个量只留一个实现，才谈得上一致。
        "ranked": n_processed(seen),
        # 与网页版同口径：标了「不投」的岗不算待办。那边的格子可以点开筛选，
        # 数字必须等于点开看到的；两个面板的同一个格子更不能给出不同的数。
        #
        # 判的是**盘上的 `status`**，不是 `stage`——`derive_stage` 里压根没有
        # `skipped` 这个取值（手动标的不投在那套阶段划分里没被表达），
        # 拿 `stage != "skipped"` 判会永远为真，等于没写。
        "materials": sum(1 for j in jobs
                         if j["app"] and j["app"].get("outreach")
                         and j.get("skipped") is not True),
        "applied": sum(1 for j in jobs if j["stage"] == "applied"),
        "interviewing": sum(1 for j in jobs if j["interviewing"]),
        # 谈钱那一格要单独数，否则它被 `interviewing` 吃掉（`_OFFER_STATUSES`
        # 上面那段记着代价）。**只认投递记录里的状态**——`interview_preps`
        # 是「练过面试题」，练过不等于拿到了 offer。
        "offers": sum(1 for j in jobs if j["offer"]),
    }
    # 「材料备好、还没投」的真实条数。口径照抄上面 `materials` 那格（有 outreach、
    # 没标不投），只多一条「还没投」——用 `stage` 判会错，`derive_stage` 是单值优先级，
    # 投过的岗 stage 就变成 `applied`，材料还在也数不到它。
    counts["ready"] = sum(1 for j in jobs
                          if j["app"] and j["app"].get("outreach")
                          and j.get("skipped") is not True
                          and j["stage"] != "applied")
    # 这批里可以**直接发**的那两档。「可以考虑」按框架是「先问清楚再决定」，
    # 和「值得投」加成一个数去催人发，等于替用户做了他还没做的决定。
    # 判词读 job dict 上的 `verdict`（`resolve_score` 的返回，深评优先）。
    # **不是 `rank_verdict`**——那是 `seen_jobs.json` 里的键名，这里的 dict 上没有，
    # `.get()` 恒为 None，`ready_strong` 就恒为 0：备好的全是「强匹配」也会被
    # 劝一句「都是可以考虑这一档，别当群发名单」。`test_ready_strong_counts_the_right_field`
    # 直接跑 build_model 数这个数，不比常量。
    # 仍要容 `粗筛：` 前缀：resolve_score 只在深评那一支剥它，没深评时原样返回。
    counts["ready_strong"] = sum(
        1 for j in jobs
        if j["app"] and j["app"].get("outreach")
        and j.get("skipped") is not True
        and j["stage"] != "applied"
        and _cli.strip_triage(j.get("verdict")
                              ).startswith(VERDICTS[:2]))  # 「可投」两档=档序前二
    seen_urls = {j["url"] for j in jobs}
    unmatched_apps = [
        a["dir"] for a in apps if a.get("outreach") and a["url"] not in seen_urls
    ]
    ranked_urls = [j["url"] for j in sorted(
        (j for j in jobs if j["stage"] == "ranked" and j["score"] is not None),
        key=lambda j: -float(j["score"])) ] if any(
        j["stage"] == "ranked" for j in jobs) else []
    # 「抓到但还没评」的数量：next_step 要用它区分「还没评」与「评完了但没一个能投」。
    n_unranked = sum(1 for j in jobs if j["stage"] == "unranked")
    ns_text, ns_cmd = next_step(counts, profile_ok,
                                ranked_urls[0] if ranked_urls else None,
                                n_unranked=n_unranked,
                                unmatched_apps=unmatched_apps)
    return {
        "jobs": jobs, "counts": counts, "profile_ok": profile_ok,
        "unmatched_apps": unmatched_apps,
        "active_user": active_user, "users": users or [],
        "next_step": {"text": ns_text, "command": ns_cmd},
        "env": env_items,
    }


