def off_supply_note(off) -> str:
    """「你关掉的那家其实是主要供给」—— 一句话，拼在任何劝人补货的建议后面。

    `off` 是 `export_web_data.off_supply()` 的返回：`(名字, 个数, 占比)` 或 None。
    判据（什么时候够格说、为什么用累计数而不是「现在还剩」）都在那边，
    **这里不重判**，只负责措辞。

    **不替他决定开不开。** 他关掉那家可能有自己的理由（命中率确实低）。
    这句话只负责让「去补货」和「供给关着」在同一屏上出现 —— 此前它们
    从不照面：实测 2026-08-24，面板一边劝「旺季用来补新的」，一边
    在渠道那一段把贡献了 84% 可投岗的那家显示成关着。
    """
    if not off:
        return ""
    name, n, share, held = (list(off) + [0])[:4]
    # **中文名两边不加空格，拉丁名要加。** 四家里「BOSS」是拉丁的，
    # 「猎聘 / 智联 / 前程无忧」是中文 —— 一律加空格会印出「你把 猎聘 关掉了」。
    name = name if re.search(r"[一-鿿]", name) else f" {name} "
    head = (f"不过你把{name}关掉了，而你能投的岗有 {share}% 是它给的"
            f"（累计 {n} 个）")
    if held:
        # **它现在打开也抓不到。** 开关是他的，封控是平台的（两份状态、
        # 两个主人，见 `off_supply`）——这句话此前只读了开关那一份，
        # 于是在封控期里照样劝「开回来」，照做的结果是抓到 0 个。
        # 供给占比那半仍然要说：那是他放行之后该动手的理由。
        # **不许说「到点之后再开」。** 2026-08-26 起封控不会自动到点解开
        # （`portal_budget._one_lane`）—— 那句话会让他一直等一个不会来的时刻。
        #
        # ⚠️ **这里带的是「已经封了多久」，不是解封时刻。** 原来插的是
        # `blockedUntil`，而那是一串 ISO：屏幕上真的会印
        # 「被平台拦着（2026-08-27T15:56 起）」—— 机器格式上屏，
        # 而且用「起」去说一个「解封」时刻，语义还是反的。
        # 判据同 `portal_budget`「报『已经封了多久』，不报『还剩多久』」。
        return (head + f"。它现在被平台拦着（已经停了 {held} 小时），"
                f"这会儿开回来也抓不到 —— 先去上面那条告警里放行它，"
                f"再回这一页的「招聘网站」那一段点一下")
    return (head + f"——不开回来，这一轮补到的会少一大半。"
            f"要开就在这一页的「招聘网站」那一段点一下")


