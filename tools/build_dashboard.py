VERDICTS = _cli.VERDICTS


#: 把结论写进 `##` 标题的那一种：`## 不满足硬性条件，不打分`。
#:
#: 锚在标题上而不是全文搜「不满足硬性条件」，因为**硬性条件那张表里逐条都有
#: 「不满足」**——全文搜会把一份正常打了分的评估也当成硬门 FAIL。
GATE_FAIL_HEADING = re.compile(r"^#{1,6}\s*\**\s*不满足硬性条件", re.M)


def is_gate_fail(text: str) -> bool:
    """这份评估的结论是「硬性条件没过」——框架规定它**不打分、也没有档位判词**。

    判据放在这里而不是 `writeback.py`，是因为**面板这条路也要用**：
    `export_web_data` 依赖本模块，反向依赖会成环。writeback 引用这一份。

    **第三种写法原来漏在这里。** 认的两种是「不打分（硬性条件过硬）」与
    「结论：不满足硬性条件」，而真实产出的那一批走的是**标题式**
    `## 不满足硬性条件，不打分`（实测活动用户那份 AI 启蒙教育评估就是这么写的）

    —— 于是它落进「读不出综合得分」那一支，被报成**解析失败**。
    守卫 `tests/_live.py` 早就认标题式了（`413a96c` 那次补的），**只有生产侧没跟上**，
    两边对同一份文件给出不同答案。

    标题是「这一份停在这儿了」的结构信号，行内措辞不是——而那张表里恰恰逐条
    写着「不满足」，所以只能锚标题。
    """
    return ("不打分（硬性条件没过）" in text
            or "结论：不满足硬性条件" in text
            or bool(GATE_FAIL_HEADING.search(text)))


def parse_evaluation(text: str) -> dict:
    """从 evaluation.md 里读出综合得分与判词。

    **必须容忍多种写法**。这是同一类 bug 的第三次（前两次：话术标题的「渠道 N：」
    前缀、邮件主题的加粗冒号位置）——AI 按 markdown 习惯写出多种合法变体，
    解析器只认一种，一部分真实数据就静默解析成空。实测 4 份真实产出里 2 份读不出来：

        **综合得分：64/100**                          ← 模板规定的写法，认
        **综合得分：约 62/100 —— 值得投，…**          ← 「约」把正则挡掉了
        **综合 = 55×0.30 + … = 62 → 「值得投」**       ← 写成加权算式，完全不认

    后果不是报错，是**深评分被丢弃、面板继续显示 /job-rank 的粗筛分**。
    所以这里按「宽进」处理：分数找 `<数字>/100` 或算式末尾的 `= <数字>`，
    判词直接在结论段里找五个档位的字面。
    """
    flags = [
        ln.strip()
        for ln in text.splitlines()
        if "|" in ln and ("FAIL" in ln or "假设值" in ln)
    ]
    # **硬性条件没过的评估要先接住，不能落到下面的正文兜底。**
    # 它的结论标题（`### 结论：不满足硬性条件`）不含五个档位词中的任何一个，
    # 于是 `banded` 为空、退回扫「结论」段正文——而翻案类评估的结论段几乎必然
    # 写着「上一轮给了 63「值得投」」这样的解释句，那句就被当成了判词。
    # 实测：某大型游戏公司 AI FDE，存档明写「结论：不满足硬性条件」，
    # 面板显示「值得投」并把它排进「可以投的岗位」。**误报只会向上**——
    # 让用户去投一个硬性条件根本不满足的岗，比不显示危险得多。
    # 门名要 `parse_gates`（在导出器里，反向依赖会成环），所以这里只给到
    # 「硬门 FAIL」四个字；带门名的完整写法由 `resolve_score` 从库里补。
    if is_gate_fail(text):
        return {"score": "", "verdict": "硬门 FAIL", "gate_flags": flags}
    # 分数：先在含「综合」的**行内**找 `NN/100`，取该行**最后一个**；
    # 再退回加权算式末尾的 `= NN`。
    #
    # 原来第一条是 `综合[^\n]{0,12}?(\d{1,3})/100`，用 12 字的邻近预算圈范围。
    # 那个预算挡掉了框架**自己的规则会生成**的写法——`candidate.md` 2026-08-14 定了
    # 专业不在 JD 清单里扣 5 分，写出来就是：
    #
    #     **综合得分：72 − 5（专业减分）= 67/100**     ← 「得分：72 − 5（专业减分）= 」17 字，超预算，读不出来
    #     **综合得分：78 − 5 = 73/100**                 ← 同一条规则、不写标签就只有 6 字，读得出来
    #
    # 一条规则的两种自然写法，一种认一种不认，而且**不认的那种恰恰是把话说清楚的
    # 那种**。后果照旧是这个函数 docstring 开头警告的那件事：不报错，深评分被静默
    # 丢弃，面板继续显示 /job-rank 的粗筛分。实测 2026-08-17 一轮 31 份深评中 3 份中招。
    #
    # 改成按行取最后一个：算式的**最终答案在末尾**，`72 − 5 = 67/100` 要的是 67。
    # `(?<![0-9])` 是必需的——不加的话贪婪回溯会从 `67/100` 里切出 `7/100`，
    # 把 67 分读成 7 分（分数只会**向下**错，比读不出来更隐蔽）。
    score_m = None
    for _ln in text.splitlines():
        if "综合" not in _ln:
            continue
        _hits = list(re.finditer(r"(?<![0-9])([0-9]{1,3})\s*/\s*100", _ln))
        if _hits:
            score_m = _hits[-1]
            break
    if score_m is None:
        score_m = re.search(
            r"^[^\n]*综合[^\n]*=\s*([0-9]{1,3})\s*(?:→|->|\s|$)", text, re.M)
    # 判词：优先锚定的写法（`## 结论：` 标题 / `**结论：**` 加粗行 / `→ **档位**`），
    # 都没有才扫全文——而且按**文中位置**取最早出现的档位，不按档位优先级。
    #
    # 原来兜底是 `next(b for b in VERDICTS if b in tail)`：按档位表顺序找，
    # 强匹配排第一。而评估正文的「判词天花板」核对句里几乎总会出现「强匹配」字样
    # （「技能 93 ≥80 → 天花板强匹配，不压」）——于是一份结论明写「值得投」的评估，
    # 面板显示成「强匹配」。解释文字污染判词，档位只会**向上**误报，比不显示更糟。
    # 锚点可能不止一个：真实评估里硬门小节也有一行「**结论：硬门全部通过，可以进入
    # 打分。**」，它在文中先出现——只取第一个会把这句**中间结论**当成判词端上屏
    # （还带着内部词「硬门」）。所以收集全部锚点，只留**含档位词**的，取**最后一个**
    # ——终局结论总在文末。
    anchored = (re.findall(r"^##+\s*结论[：:]\s*(.+)$", text, re.M)
                + re.findall(r"\*\*结论[：:]\s*([^\n*]{1,30})", text)
                + re.findall(r"→\s*\*\*([^\n*]{1,12})\*\*", text))
    banded = [next(b for b in VERDICTS if b in raw)
              for raw in anchored if any(b in raw for b in VERDICTS)]
    if banded:
        verdict = banded[-1]
    else:
        tail = _section(text, "结论") or text
        hits = [(tail.index(b), b) for b in VERDICTS if b in tail]
        verdict = min(hits)[1] if hits else ""
    return {
        "score": score_m.group(1) if score_m else "",
        "verdict": verdict,
        "gate_flags": flags,
        "advice": _section(text, "建议").strip(),
    }


#: 接回软折行时，那个位置本来该是空格还是什么都没有。
#: 折点落在**本来就允许断开**的地方：中文之间不需要空格；中英、中数之间按中文排版
#: 惯例要一个空格；英文单词之间那个换行原本就是个空格。所以——**至少一边是拉丁
#: 字母或数字**时补空格，两边都是汉字/假名时不补。标点两侧一律不补（标点自带间距，
#: 「。」后面再加空格就是多的）。
_ASCII_WORD = re.compile(r"[0-9A-Za-z]")
_HAN = re.compile(r"[぀-ヿ一-鿿]")     # 假名 + 汉字，**不含**标点


#: 另起一块的行——接回去会把列表压成一行。这不是自造的方言，是 markdown 自己的
#: 块级标记；列表项的续行（不带这些标记的缩进行）按 markdown 的惰性续行照常接回。
_BLOCK_START = re.compile(r"""^[ \t]*(
      [-*+][ \t]                 # 无序列表
    | \d+[.)][ \t]               # 有序列表
    | >                          # 引用
    | \#{1,6}[ \t]               # 标题
    | \|                         # 表格行
    | (-{3,}|\*{3,}|_{3,})[ \t]*$  # 分隔线
)""", re.X)


def unwrap_soft_wraps(text: str) -> str:
    """把 markdown 的**软折行**接回去，只留作者真正想要的分行。

    这里修的是一处**约定不一致**：`outreach.md` 是一段一行写的，`interview_log.md`
    却按 80 列硬折行——同样一个 `\\n`，前者是真断行，后者只是排版。渲染层看到的
    都只是 `\\n`，光靠 CSS 分不出来，所以语义必须在**取数层**定死。

    定的就是 markdown 自己的规矩，不另造一套：

    - 段落内的单个换行是**软折行**，接回去（怎么接见 `_ASCII_WORD` 那段注释）
    - **空行**才是分段，保留
    - `- ` / `1. ` / `> ` / `#` / `|` 开头的行**另起一块**，不接
    - ``` 围栏里的原样不动——代码的换行和缩进都是内容

    > 曾经反过来修过一次：只在 CSS 上加 `white-space: pre-line`，让所有 `\\n`
    > 都变成硬换行。结果 4 个换行里 3 个是 80 列折行，句子被从中间劈开，
    > 「升级成 / 可用产品」还是断的——只是把「中间多个空格」换成了「中间硬换行」。
    > **换行该不该是换行，取数层才知道；CSS 只能一视同仁。**

    ⚠ **不要顺手推广到 `parse_outreach`。** 那个文件是**一段一行**写的，相邻两行
    本身就是结构：网申自评里「1. 对岗位的理解」下面紧跟正文，接回去就成了
    「1. 对岗位的理解这个岗位要解决的是…」，实测 14 行压成 7 行。
    **约定是逐文件的，由那个文件的解析器各自认。**
    `test_interview_log.py` 里有一条钉死这个边界。
    """
    # 围栏按**外层**跟踪，不用奇偶开关：只有裸 ``` 闭合外层，带 info string 的
    # （```json 之类）一律当作嵌套开头。奇偶会被嵌套围栏带偏，翻到最后正好反过来，
    # 于是**围栏外的软折行不再被接回去**——面板上就是句子中间断行，而且一声不吭。
    #
    # 同一个写法 2026-08-20 在 `tests/test_workflow_prose_is_chinese.py` 上真栽过
    # （判据少报了 15 行英文，而少报比没有判据更坏）。这里是预防：拿活动用户的
    # 805 份归档实测，**围栏数为奇数的 0 个、嵌套的 0 个**，改前改后输出逐字节相同。
    #
    # **闭合按反引号个数配对（CommonMark 的规矩），不是「谁先来谁算」。**
    # 上一版把 `depth` 当成 0/1 的开关：外层是 ```` 时，里面那个三反引号
    # 代码块的**闭合**行（裸 ```）会被当成外层的闭合，此后整块正文都被当成
    # 围栏外的散文接了起来。实测：
    #     ````markdown / ```json / {} / ``` / 正文一 / 正文二 / ````
    # 产出 `正文一正文二` —— 粘在代码块里面。`tests/md.fenced_lines` 早就是
    # 按游程长度配的，两边现在是同一套语义。
    out: list[str] = []
    fence = 0                      # 当前外层围栏的反引号个数；0 = 不在围栏里
    for line in text.split("\n"):
        s = line.lstrip()
        if s.startswith("```"):
            run = len(s) - len(s.lstrip("`"))
            info = s.lstrip("`").strip()
            if not fence:
                fence = run
            elif not info and run >= fence:
                fence = 0          # 只有**不带标签、且不比开头短**的那行能闭合
            out.append(line)
            continue
        depth = fence
        # `out[-1]` 是围栏行时也不接 —— **围栏行本身是块边界**。
        # 不挡的话，闭合 ``` 后面紧跟的正文会被粘到那一行上，把围栏整个弄坏：
        #     ```           →   ```这是围栏后的第一句
        #     这是围栏后的第一句
        # **它不是假想的**：2026-08-20 拿活动用户的 805 份归档实测，
        # 围栏行后面紧跟非空行的地方有 181 处，其中**闭合**围栏后紧跟正文的 1 处，
        # 那一份 `posting.md` 改之前产出的正是
        #     ```（第 3 条及以后未在列表页右栏完整渲染，…）
        # ——围栏被那句备注粘住，整个废掉。这条是那 1 处的修复。
        # 是本函数自己的变异用例把它暴露出来的：先修围栏跟踪，再写用例，用例露出这个。
        if (depth or not out or not line.strip() or not out[-1].strip()
                or out[-1].lstrip().startswith("```")
                or _BLOCK_START.match(line)):
            out.append(line)
            continue
        prev, cur = out[-1].rstrip(), line.strip()
        a, b = prev[-1:], cur[:1]
        both_wordish = ((_ASCII_WORD.match(a) or _HAN.match(a))
                        and (_ASCII_WORD.match(b) or _HAN.match(b)))
        one_latin = _ASCII_WORD.match(a) or _ASCII_WORD.match(b)
        out[-1] = prev + (" " if both_wordish and one_latin else "") + cur
    return "\n".join(out)


def parse_interview_log(path: Path) -> list:
    """`interview_log.md` → `[{round, date, stage, scene, qa:[{q,a,feedback}]}]`。

    格式由 `interview.md` 的 Step 4b 规定：`## 第 N 轮 · 日期 · 阶段`，其下
    `### Q1 问题` + `**答**：` + `**反馈**：`。

    **宽进**：轮次/日期/阶段任何一段缺了都照样收，缺的留空——练习记录是手写的，
    为一个格式瑕疵丢掉整轮问答，比少显示一个日期糟得多。但**不猜**：读不出的
    字段留空字符串，不去推断。
    """
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8", errors="replace")
    rounds = []
    # 以 `## ` 切轮次；`### ` 是轮内的题
    for chunk in re.split(r"^##\s+(?!#)", text, flags=re.M)[1:]:
        head, _, body = chunk.partition("\n")
        parts = [p.strip() for p in re.split(r"[·•]", head) if p.strip()]
        rnd = next((m.group(1) for p in parts
                    if (m := re.search(r"第\s*(\d+)\s*轮", p))), "")
        date = next((p for p in parts if re.fullmatch(r"\d{4}[-/.]\d{1,2}[-/.]\d{1,2}", p)), "")
        stage = next((p for p in parts
                      if p and not re.search(r"第\s*\d+\s*轮", p) and p != date), "")
        scene = ""
        m = re.search(r"^\s*[-*]\s*场景[：:]\s*(.+)$", body, re.M)
        if m:
            scene = m.group(1).strip()
        qa = []
        for q in re.split(r"^###\s+", body, flags=re.M)[1:]:
            qhead, _, qbody = q.partition("\n")
            ans = re.search(r"\*\*答\*\*[：:]\s*(.*?)(?=\n\s*\*\*反馈\*\*|\Z)",
                            qbody, re.S)
            fb = re.search(r"\*\*反馈\*\*[：:]\s*(.*)", qbody, re.S)
            qa.append({
                # 去掉「Q1 」这类编号前缀，编号由界面自己排
                "q": re.sub(r"^Q?\d+[.、）)\s]*", "", qhead.strip()).strip(),
                # 两个字段都是**多行正文**，都要过 `unwrap_soft_wraps`
                "a": unwrap_soft_wraps(ans.group(1).strip()) if ans else "",
                "feedback": unwrap_soft_wraps(fb.group(1).strip()) if fb else "",
            })
        if qa or scene:
            rounds.append({"round": rnd, "date": date, "stage": stage,
                           "scene": scene, "qa": qa})
    return rounds


#: 逐岗的下一步。**与流水线那条 `next_step` 不是一回事**：那条回答「整体该干什么」，
#: 这条回答「**这个岗**卡在哪」。同一时刻两者可以指向不同的事——整体也许该去投别的岗，
#: 而这个岗正等着记面试结果。
def is_optional(item: dict) -> bool:
    """这个依赖是**可选**的吗（不装也能正常用）。

    可选项不能算进「缺 N 项」：pdftotext / Bun / 浏览器取数不装完全能用，
    把它们算进去会让新用户以为出了大问题，然后去装一堆不需要的东西。

    **两个面板共用这一个判断。** 原来它是单页版里的一个内嵌函数，而导出给网页版的
    `envItems` 干脆把 `optional` 字段丢了——于是一台没装 Bun 的机器上，网页版会说
    「还差 Bun（可选）」并每次默认展开，催人去装一个他不需要的东西。

    认显式标记；老数据（没这个字段）才退回嗅 label 字面。
    """
    if "optional" in item:
        return bool(item["optional"])
    return "可选" in (item.get("label") or item.get("name") or "")


def is_parked(job: dict) -> bool:
    """这个岗还是不是待办。**「不催它」和「不数它」必须是同一个判断。**

    三类：标了不投（用户的判断）、已下线（外面的事实）、重复挂法（同岗在别处，
    不单独占行）。它们都进搁置区，页面的行集看不到。

    原来只有 `funnels_of` 知道这件事，`job_next_step` 不知道——于是
    2026-08-20 实测 90 个岗一边躺在搁置区、一边在详情里被告知
    「材料就绪，还没投——复制开场白、开职位链接自己投出去」：
    77 个是用户自己标的不投，**12 个的职位已经关了**。
    催一个关掉的岗去投，比不催更糟。
    """
    return bool(job.get("dupOf") or job.get("skipped") or job.get("expired"))


def is_out_verdict(verdict: str) -> bool:
    """判词说这个岗出局了吗（硬门没过 / 已下线 / 跳过 / 不建议）。

    **和 `is_parked` 是同一族的两半**：那半问「状态说它还是不是待办」，
    这半问「判词说它还是不是待办」。`funnels_of` 一直两个都问，
    而 `job_next_step` 只问了前一半 —— 于是 2026-08-26 出现了
    `is_parked` 的说明里记的那个形状的**第二遍**：
    一个岗材料做完之后判词才降到「跳过」（发现同一家的这个岗早就投过），
    页面一边把它算作出局、一边在详情里催「材料就绪，还没投，快去投」。

    这个函数原来住在 `export_web_data`，而催与不催的那处在这个文件里，
    够不着。搬过来放在 `is_parked` 旁边，两半从此在同一屏上。

    ## 与 `is_sellable` 不是同一个问题

    这个函数管的是「哪些岗不进流水线格子」—— 一个硬门没过的岗不该出现在可投
    名单里，但它要是**已经投出去了**，「已投递」那格就必须数它，
    否则格子上的数和点开看到的行数对不上。

    **黑名单，前缀容错。** 判词带门名后缀是常态（`不满足硬性条件 (学历)`），
    所以用 startswith 不用 ==。2026-08-13 就是精确匹配落空，
    让硬门没过的岗混进了可投名单。

    ## **「已下线」也是出局，而且是最确定的那种**

    它原来不在这张表里，靠的是另一条路兜住：`funnels` 前面先跑 `is_parked`、
    `archive.pick` 先看 `status == "expired"`，两处都会把这些岗排掉，
    于是漏了也看不出来。实测活动用户 2026-08-23：4 个判词以「已下线」开头的岗，
    4 个都已被 `is_parked` 排掉 —— **补进来一个结果都不变**。

    那为什么还要补：这个函数管的就是「判词说出局」这一侧。它漏掉最确定的
    一种，等于把正确性押在「状态那一侧一定同时也对」上 —— 而判词是打分器
    写的、状态是下线探测写的，两者本来就可能不同步（真出现时那个岗会永远
    留在热库，而 `archive` 存在的理由正是「热库不涨」）。

    **不能加进 `GATE_FAIL_PREFIXES`**：那张表是给门名解析用的
    （`gate_in_verdict` 要从里面抠出是哪道门），而「已下线」不是一道门。
    """
    v = (verdict or "").strip()
    return (v.startswith(_cli.GATE_FAIL_PREFIXES) or v.startswith("已下线")
            or "跳过" in v or "不建议" in v)


#: 静默多少天算「该催了」。**正本在 `followups.QUIET_DAYS`**，这里只引用。
#:
#: 那个常量的说明里点名了这句话：「面板的『超过十天没动静可以催一次』……
#: 都以它为准」。**而它以前不是** —— 下面那句里写的是中文数字「十天」，
#: 和常量之间没有任何连接：改成 14 天，面板照样说「十天」。
#: （2026-08-21 通读逐岗「下一步」时发现。）
#:
#: **裸 import，不给兜底。** 原来这里是 `try: … except Exception: QUIET_DAYS = 10`
#: ——而兜底值就是那个字面量本身，也就是把刚收拢掉的那份抄件又抄了回来：
#: 哪天正本改成 14，只要 import 因为任何原因失败，面板会安安静静地继续说 10，
#: 而 `/job-outcome followup` 说 14。`except` 还把失败的原因一起吞了。
#: 本文件对 `tracker` 的 import 就写着「没有兜底，它挂了就该炸在 import」，
#: 同一条规矩。`followups` 只依赖标准库 + `_cli` + `tracker`，都在这之上，
#: 不存在循环。
from followups import QUIET_DAYS, parse_date  # noqa: E402


def _days_since(day: str, today: _dt.date | None = None) -> int | None:
    """这个日期到今天几天。读不出来返回 None —— 不猜。

    **日期解析走 `followups.parse_date`。** 台账是**人手填的**，那个函数为此
    认四种写法（`2026-07-15` / `2026/07/12` / `2026.07.12` / `2026年7月12日`），
    而这里原来只认 ISO：同一行 `2026/07/12` 在 `/job-outcome followup` 里
    判「该催了」，在面板同一个岗上却读不出日期、退回那句将来时的
    「超过 10 天没动静可以催一次」。两处说同一件事就该用同一个解析器。

    `(day or "")` 挡不住非字符串（手改过的 CSV/JSON 里的整数、日期对象），
    那会抛 `AttributeError` —— 一行坏数据就能把整份导出掀翻，
    而下面本来就写好了「日期读不出来」那一支。所以三种异常一起接。
    """
    try:
        s = (day or "").strip()
        # 整串先试（`2026年11月12日` 比 10 个字符长），不成再切前 10 个
        # ——那是为 `2026-08-21T10:00` 这种带时间的写法留的。
        d = parse_date(s) or parse_date(s[:10])
    except (TypeError, ValueError, AttributeError):
        return None
    if d is None:
        return None
    return ((today or _dt.date.today()) - d).days


#: 「建议」那一节以什么开头就算「别投」。**只看开头**，见 `job_next_step` 里
#: 那段说明 —— 这一节里顺口提到「不投」的句子太多了。
_AGAINST = ("不投", "别投", "不建议投", "不要投")


def _advises_against(job: dict) -> bool:
    """这个岗的评估结论是不是「先别投」。取不到「建议」就当没意见。

    **两种形状都要认。** 这个函数被两条路调用，而它们手上的 job 长得不一样：

        build_dashboard 的投递记录   job["evaluation"]["advice"]   （嵌在里面）
        export_web_data 导出的岗     job["advice"]                 （平铺）

    只认其中一种就是「本机跑得通、面板上没生效」—— 实测 2026-09-02 第一版
    只读嵌套那种，导出之后 13 个岗照旧印着「材料就绪，还没投，快去投」，
    而 `advice` 字段明明已经在 `data.json` 里了。
    """
    adv = (job.get("advice")
           or (job.get("evaluation") or {}).get("advice") or "").strip()
    adv = adv.lstrip("*_ -—·").lstrip()
    return adv.startswith(_AGAINST)


def job_next_step(job: dict, today: _dt.date | None = None) -> dict | None:
    """`{text, command?}`，没有可推进的动作时返回 None。

    倒着判断，与 `next_step` 同一原则：从最靠后已经发生的事开始。正着判会给出
    倒退的建议——比如已经面完的岗，因为「有材料」而被建议「去投递」。

    `today` 只为测试注入，正常调用不传。
    """
    applied = job.get("applied") or {}
    status = (applied.get("status") or "").strip().lower()
    company = job.get("company") or ""
    # 终结态用 tracker 的那份，不另抄——这里原来抄的一份漏了 `no_response`
    # （下划线体），同一条旧记录 followups 说「已终结」、这里却还催。
    if status in tracker.FINAL_STATUSES:
        return None                                   # 已结案，没有下一步
    # offer 要**先于** interview 判。合在一起给 `/job-interview` 是错的：拿到 offer
    # 之后该做的是算可守区间、过背调红线、和别的 offer 比——那是 `/job-offer`，
    # 不是再练一轮面试题。这一步给错，用户就会在最该谈钱的时候去背题。
    if status in _OFFER_STATUSES:
        return {"text": "拿到 offer 了。谈薪区间、背调红线（报的数字要和个税记录对得上）、"
                        "多个 offer 怎么比，都在这一步",
                "command": f"/job-offer {company}"}
    if status == "interview":
        n = len(job.get("interviewLog") or [])
        return {"text": f"进面试了{'，已练 %d 轮' % n if n else '——还没练过'}。"
                        "备面与模拟面在对话里跑",
                "command": f"/job-interview {company}"}
    if applied:
        # 「有消息了回来记一笔」删了：记那一笔的按钮就摆在这句话右边，
        # 一句话又教一遍它旁边那个按钮怎么用，24 行里每行都教一遍。
        #
        # **按已经等了多久说话。** 原来这句是静态的：不论投出去 3 天还是 11 天，
        # 一律写「超过十天没动静可以催一次」—— 一个**将来时的条件句**，
        # 而对已经过线的岗，那件事早就发生了。
        # 实测（2026-08-21）：84 个已投的岗全是这一句，其中 18 个已经过了线；
        # 同一份数据里「投出去的那些怎么样了」把它们归进了「大概率没戏」，
        # **而每个岗自己那一行毫不知情**。
        # 违反的是 AGENTS.md 那条「按**当前状态**给下一步」。
        day = (applied.get("date") or "").strip()
        n = _days_since(day, today)
        if n is not None and n >= QUIET_DAYS:
            head = f"{day} 投的，已经 {n} 天没动静"
            # 这里原来第一句是「可以催一次」。2026-08-29 按用户裁定去掉
            # （`AGENTS.md`「跟进归用户，工具不催」）——催不催归他，
            # 这一行只说事实，加上他在这儿真能点的那个按钮。
            tail = ("——确认没戏了就点右边的「没下文」，"
                    "别让它一直挂在「还在等」里")
        elif n is not None:
            # 「0 天前」不是话。当天投的就说「今天」。
            when = "今天投的" if n <= 0 else f"{day} 投的（{n} 天前）"
            head = f"{when}，等回复"
            tail = ""
        else:                            # 日期读不出来：退回原来那句，不猜
            head, tail = f"{day} 已投，等回复", ""
        return {"text": (head + tail).strip(),
                "command": f"/job-outcome {company}"}
    # 位置在「在飞的」之后、催投递之前：已投/面试/offer 讲的是**已经发生的事**，
    # 那几步照给；从这里往下都是在催他**开始**做点什么，而搁置的岗不该被催。
    if is_parked(job):
        return None
    # **判词出局的岗不催去投，哪怕材料已经做好了。**
    #
    # 这一条原来在下面 —— 在 `if job.get("materials")` **之后**。于是判词
    # 后来降档的岗（材料先做好、之后才发现硬门没过或已经投过同一个岗）
    # 永远走不到那儿，页面一直催「材料就绪，还没投，快去投」。
    # 实测 2026-08-26：一个岗材料出完之后才对上台账里 13 天前的同一次投递，
    # 判词改成「跳过」，而详情里那句催投的话原样还在。
    #
    # 判据与 `funnels_of` 同一个函数（`is_out_verdict`）——
    # 「不催它」和「不数它」得是同一个判断，见 `is_parked` 的说明。
    if is_out_verdict(str(job.get("verdict") or "")):
        return None
    # **评估自己写着「不投」的岗，不催去投。**
    #
    # 这是上面 `is_out_verdict` 那条的同一形状再深一层。判词是打分器给的档，
    # 而「建议」是读完这个岗之后写下的结论 —— 两者可以合法地不一致：
    # 判词「可以考虑」＋建议「不投。同一个岗有薪资更高的挂法，投那一条」。
    #
    # 问题不在它们不一致，在于**「建议」没有任何消费方**：`data.json` 里
    # 从来没有这个字段，于是屏幕上只剩判词那一半。
    # 实测 2026-09-02：50 份深评的「建议」以「不投」开头，其中 13 个的
    # 「下一步」正印着「材料就绪，还没投——复制开场白、开职位链接自己投出去」。
    # `AGENTS.md` 管这个叫「同一份文档一边发出邀请，一边把门关上」。
    #
    # **只认开头**：`建议` 那一节里提到「不投」的句子太多了
    #（「不投这一条，投那一条」「若不投也可以…」），按包含判会把一堆真该投的
    # 也拦下来。开头那一句才是这一节的结论。
    if _advises_against(job):
        # **一条引导只给一个动作**（`AGENTS.md`「每一处引导都要写出该敲的命令」
        # 第 3 条）。这里确实有分支，所以按那一条允许的写法**写清哪种情况做哪件事**：
        # 同意 → 点这一行的按钮（不必敲命令）；不同意 → 重跑一遍那条命令。
        #
        # 理由不必在这儿复述：`advice` 已经渲染在这个岗的详情最上面。
        return {"text": "评估的结论是先别投（理由在上面那行）。"
                        "同意就点这一行的「不投这个岗」；"
                        "觉得这个判断不对，就重跑一遍：",
                "command": f"/job-apply {job.get('url') or '<职位链接>'}"}
    if job.get("materials"):
        # 投递本身只能你自己做（这个仓库不替你提交）。但**投完那一步**有命令，
        # 原来这条却什么都不给——于是「投出去」之后线索就断了，
        # 投递记录一直是空的，后面的催进度、备面、报表全都无从谈起。
        # 「投完回来记一笔」**必须留着**：它交代的是这条命令的先后位置——
        # 投是你自己去投的，`/job-outcome` 是投完之后才敲的。没有这半句，
        # 一条命令紧跟在「去投递」后面，读起来就像这条命令能替你提交
        # （`test_interview_log.PerJobNextStepGoesBackwards` 盯着这件事）。
        # 删掉的是再往后那半句「后面的催进度和备面都靠这条记录」——那是在给
        # 记一笔找理由，而它会出现在每一个备好料的岗上。
        return {"text": "材料就绪，还没投——复制开场白、开职位链接自己投出去，投完回来记一笔",
                "command": f"/job-outcome {company}"}
    if job.get("score") is None:
        return None                                   # 硬性条件没过/已跳过
    # **只有可投的两档才催出材料。** 唯一的守门原来是 `score is None`，
    # 而「不建议」「跳过」是**有分数的**——于是它们照样被催去 `/job-apply`。
    # 实测（2026-08-20）461 个「还没出材料」里：不建议 265、跳过 9，
    # 合计 274 个岗在教用户敲一条会白跑的命令——`job-apply.md` 的批量闸门
    # 明写这几档「停在这里，只落 evaluation.md，不出开场白」。
    #
    # 「可以考虑」那 175 个单独给话：04 的定义是「**先问清楚**关键信息再决定」，
    # 它是一个待办不是一个动作。催他去出材料，等于替他把「要不要投」这个
    # 还没做的决定当成已经做了。
    verdict = _cli.strip_triage(job.get("verdict"))
    if verdict == VERDICTS[2]:                   # 可以考虑
        return {"text": "这一档要先问清楚再决定投不投——想连它一起备料就跑下面这条",
                "command": "/job-apply 可以考虑"}
    if verdict in VERDICTS[3:]:                  # 不建议 / 跳过：不催
        return None
    # 判词缺失或认不出时**照常催**。方向要往「多说一句」偏，不往「静默吞掉」偏：
    # 多催一次的代价是用户跑一条没产出的命令；静默吞掉的代价是一个真能投的岗
    # 从「下一步」里整个消失，而他不会知道少了什么。
    return {"text": "还没出材料", "command": f"/job-apply {job.get('url') or ''}"}


def find_applications(apps_dir: Path) -> list:
    apps = []
    if not apps_dir.is_dir():
        return apps
    for d in sorted(apps_dir.iterdir()):
        if not d.is_dir():
            continue
        try:
            rec = {
                "dir": d.name,
                "url": "",
                "outreach": None,
                "evaluation": None,
                "resume": (d / "resume.pdf").is_file(),
                "interview_preps": sorted(
                    p.name for p in d.glob("interview_prep_*.md")
                ),
                "interview_log": parse_interview_log(d / "interview_log.md"),
            }
            o = d / "outreach.md"
            if o.is_file():
                rec["outreach"] = parse_outreach(o.read_text(encoding="utf-8"))
                rec["url"] = rec["outreach"]["url"]
            if not rec["url"]:
                p = d / "posting.md"
                if p.is_file():
                    # 标签宽进：实测 6 份真实归档里 3 份写的不是「原始链接：」——
                    # 有半角冒号的、有只写「链接：」的，全靠 outreach.md 那行侥幸
                    # 兜底才没丢材料。少写一行，整个投递目录就接不上职位：材料
                    # 消失、硬性条件消失，且无声。标签变体 + 冒号全半角都认；
                    # 都对不上再退到「文件头部第一个链接」——posting.md 开头是
                    # 元信息块，正文里雇主写的链接混不进前几行。
                    pt = p.read_text(encoding="utf-8")
                    m = (re.search(r"(?:原始链接|职位链接|链接|URL)\s*[：:]\s*(https?://\S+)", pt)
                         or re.search(r"(https?://\S+)",
                                      "\n".join(pt.splitlines()[:12])))
                    if m:
                        rec["url"] = m.group(1)
            e = d / "evaluation.md"
            if e.is_file():
                rec["evaluation"] = parse_evaluation(e.read_text(encoding="utf-8"))
            apps.append(rec)
        except (UnicodeDecodeError, OSError) as exc:
            # 静默 continue 会让整个投递目录从面板上消失：三渠道话术与简历链接都不见，
            # counts["materials"] 归零，下一步又变回「给头部岗生成材料」——叫用户对一个
            # 材料已经在磁盘上的岗重跑 /job-apply。至少要说出来。
            print(f"警告: 跳过投递目录 {d.name}（{type(exc).__name__}: {exc}）——"
              f"该岗的材料不会出现在面板上", file=sys.stderr)
            continue
    return apps


