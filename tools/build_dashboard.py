def next_step(counts: dict, profile_ok: bool, top_ranked_url=None,
              n_unranked: int = 0, unmatched_apps=None, n_sellable=None):
    """(说明, 可选命令) —— 据流水线状态给本步最该做的一件事。

    **倒着判断**，从流水线最靠后已经发生的事开始。早先的实现是从前往后（抓→评→材料→
    投→面试，第一个不满足的就是下一步），那假设状态严格线性推进；而真实状态会跳跃，
    靠前的条件先命中就会给出**倒退的建议**。两个实测到的例子：

    - 唯一的职位是硬门 FAIL：`ranked` 计数 > 0（它确实被评过），于是说「排好了，给头部岗
      生成材料」；但 gate_fail 的岗不该投，`top_ranked_url` 是 None，命令退化成
      `/job-apply <职位URL>` 占位符 —— 等于让用户去投一个不存在的岗。
    - 已投但那个岗已过期：`status` 是 `expired` 不是 `ranked`，`ranked` 计数为 0，
      于是说「还没排名：跑 /job-rank」，而用户其实已经投了、在等回复。

    参数里 `top_ranked_url` 为 None 表示**没有可投的已评岗**（全是 gate_fail / 低分），
    这跟「还没评」是两件事，不能共用一条建议。
    """
    # 资料没建是唯一的前置硬条件：没有它，后面每一步的产出都不可信。
    if not profile_ok:
        return ("先建资料：跑 /job-setup 填好你的求职资料", "/job-setup")

    # 以下从后往前。
    # **钱排在面试前面。** 判据和逐岗那条是同一条（见 `_OFFER_STATUSES`）：
    # 拿到 offer 之后该做的是算可守区间、过背调红线、和别的 offer 比，
    # 不是再练一轮面试题。用 `.get`：老调用方传的 counts 里没有这一格。
    if counts.get("offers", 0) > 0:
        return ("拿到 offer 了，先谈钱：可守区间、背调红线、多个 offer 怎么比",
                "/job-offer <公司>")
    if counts["interviewing"] > 0:
        return ("有面试了，去备面", "/job-interview <公司>")

    # ── 零回音**不再给出「下一步」** —— 用户 2026-08-29 裁定 ──
    #
    # 原话：「job-outcome followup 是干嘛的，我之前不是说了没必要 followup 吗，
    # 真有反馈，应该用户自己去跟进，在这里记录意义不大」。
    #
    # 这里原来有一整支：投出去一片、一个回音都没有时，把「先催一遍」
    # （`/job-outcome followup`）印成唯一的下一步，后面还接一段解读
    # （是简历的问题 / 是开场白的问题 / 是时机的问题）。整支撤掉，
    # 状态交给下面的流水线判据（有材料没发 → 先发；没有 → 接着抓）。
    #
    # **注意这条裁定此前说过一次，而谁也没写下来** —— 于是它今天原样冒了
    # 出来，用户第二次说同一句话。规则只活在一次会话里，换一轮就整条丢掉；
    # 正本现在在 `AGENTS.md`「跟进归用户，工具不催」那一节。
    #
    # 撤的是**推动作**，不是数据：`decided` / `replied` 都还在，
    # 投后分析（`/job-html-report`）照常算回复率。
    # （`_why_silent` 跟着推动作一起删了 —— 它只服务于催的那条路。）
    # `/job-outcome followup` 这条命令本身也保留 —— 他想催的时候敲得到，
    # 只是工具不再替他决定该催了。

    # **名单见底优先于「去投递」。** 这一条原来整个不存在：只要投过一次，
    # 下面 `applied > 0` 那支就永远接管，在「还有 N 个材料没投」与
    # 「都投出去了，等回复」之间来回，**没有任何一条路通向补货**。
    # 而同一时刻终端自检说的是「跑 /job-scrape 补充名单 —— 手上在跑的岗越少，
    # 越不该停下找岗」（那是 2026-08-13 之前的话，2026-08-29 改成 `/job-auto`）。
    # 两份实现给出不同的行动建议，用户看哪个算哪个。
    #
    # 放在这里而不是更后面：手上还有 3 个能投的岗时，「去投那 3 个」和
    # 「去补货」都对，但**补货有前置时间**，晚说不如早说；而面试已经在跑
    # 时不抢它的位置（那一条更要紧，所以在它之后）。
    # `ranked > 0` 这道门：一次都没评过的全新状态谈不上「见底」——放它落到
    # 下面 `n_unranked > 0` 那条本来就有的干净分支（「还有 N 个抓到但没评的
    # 职位：跑 /job-rank」），不在这里用「名单快见底」的措辞吓人。
    if (n_sellable is not None and n_sellable < SHORTLIST_FLOOR
            and counts["ranked"] > 0):
        # 有「抓到但没评」的积压时，补货的第一步是把库存评完，不是再去抓。
        # 第一版没有这个分支：刚 /job-scrape 完 543 个、0 个已评的新用户，名单当然
        # 是 0——于是被指回 /job-scrape，/job-scrape → /job-scrape 死循环（新抓的没评分，
        # n_sellable 永远是 0），而 doctor 在同一状态下说的是「跑 /job-rank」。
        # 见底分支插在所有「还没评」分支**之前**，就必须自己把这种状态让出去。
        # `n_unranked` 的缺省值是 `None`，而这里原来直接 `n_unranked > 0` ——
        # **任何省掉它的调用方都会炸 `TypeError`，整个面板出不来**。
        # 现有两个调用方都传了数，所以它一直没露；2026-10-14 把
        # `doctor.count_restock` 接上「读不到就交回 None」的约定之后，
        # `None` 成了一个真实可达的值。
        # 判据用 `isinstance`，与上面 `n_sellable` 那一行同一个写法。
        if isinstance(n_unranked, int) and n_unranked > 0:
            return (f"可以投的名单快见底，而还有 {n_unranked} 个抓到没评的："
                    f"先跑 /job-rank 把库存评完，不够再抓", "/job-rank")
        left_txt = f"只剩 {n_sellable} 个" if n_sellable else "一个都不剩了"
        # 老提示教人抓完手动接打分，已过时：/job-scrape 抓完默认自动评分
        # （job-scrape.md Step 5.5），面板再教人手动接一步，等于把已经焊死的接缝
        # 重新说成断的。
        #
        # **2026-10-14 两处改动，都是这一支自己的问题：**
        #
        # **一、命令从 `/job-scrape` 换成 `/job-auto`。** 它抓完自动评分，但
        # **不出材料** —— 敲完他手上是一排没材料的岗，还得再敲一条才走得到
        # 能发的那一步。`tests/test_the_next_step_is_the_spine.py` 正文原话
        # 就是这个，而终端那一支因此被钉成 `/job-auto`。面板这一支给
        # `/job-scrape`，等于同一个仓库里对同一件事有两种答案。
        # `/job-auto` 把抓、评、出材料一气跑完，**并不丢这一支的理由** ——
        # 上面那句「补货有前置时间，晚说不如早说」照样成立，它先抓的。
        #
        # **二、「手上在跑的岗」这个说法和那个数对不上。** `n_sellable` 走
        # `is_sellable`，含「可以考虑」；而「可以考虑」按 `04` 的定义是
        # **先问清楚再决定，是一个待办不是一个动作**，不是「在跑」。
        # 4 个「可以考虑」+ 0 个强档时，原来那句会说他「手上只剩 4 个在跑的」——
        # 而他实际有 **0 个能直接发**。删掉「在跑」，数与话就对上了。
        # **数本身不动**：那个数与页面行集同源是刻意的（见 `export_web_data`
        # 里 `n_sellable` 上面那段），要改得连页面标签一起改，那是另一件事。
        return (f"可以投的岗位{left_txt}——越少越不该停下找岗。"
                f"跑一轮 /job-auto 补货，抓完会自动评分排序，接着出材料"
                + (f"。{off_supply_note(counts.get('off_supply'))}"
                   if off_supply_note(counts.get("off_supply")) else ""),
                "/job-auto")

    if counts["applied"] > 0:
        # `applied` 是**已记录的投递数**，不是「有一笔没记的投递」。
        # 原来这里直接说「投了，先把这笔记下来 → /job-outcome」，于是只要投过一次，
        # 这条建议就**永远不再变**：刚跑完 /job-outcome 它还让你去跑 /job-outcome，
        # 投了 20 个全记完也一样。判据说的和文案说的不是一件事。
        #
        # 已经有投递记录之后，真正该做的下一件事只有两种：把剩下备好的材料投出去，
        # 或者等回复、该催的时候催。
        # **直接数「有材料且没投」，不要拿 materials − applied 去减。**
        # 那个减法假设「投过的岗一定留了材料目录」，而这不成立：手动投的、
        # 或 /job-outcome 直接记一笔的岗，`applied` 有、`materials` 没有，
        # 减法就会把它多减一次。2026-08-12 实测面板报 104，实际 105——
        # 差的正是这么一个岗（投了但没材料目录）。
        # 计数由调用方按各自的行集算好传进来，口径与页面一致；
        # 没传时退回旧减法，只为兼容老调用点。
        left = counts.get("ready")
        if left is None:
            left = counts["materials"] - counts["applied"]
        if left > 0:
            # 投递在招聘网站上做，这里没有命令可跑；但**投完那一步有**——
            # 引导要一直给到「下一个能敲的命令」，不能停在「去投吧」。
            #
            # 季节那一句原来挂在「零回音」那一支上，那一支 2026-08-29 撤了
            # （见下面那段裁定），它就成了没有调用方的死代码 —— 而它自己有
            # 10 个测试文件的覆盖（春节冻结、国庆、校招/社招两套日历）。
            # 接到这里：它回答的本来就是「现在该不该发、发得及不及时」，
            # 和这一支是同一件事，**不是**对回音的解读。
            _head = _ready_text(left, counts.get("ready_strong"),
                                counts.get("ready_old") or 0,
                                counts.get("ready_asked"),
                                counts.get("expired_unsent") or 0)
            _season = season_note(counts.get("applied_months") or [],
                                  _dt.date.today(), counts.get("stage"),
                                  counts.get("ready") or 0,
                                  counts.get("off_supply"))
            # 两段各自成句，接缝要补标点：`_ready_text` 收在「）」上、
            # 季节那句起手是「另外：」，直接相加会读成「…下线）另外：」。
            if _season and not _head.rstrip().endswith(("。", "；", "，")):
                _head = _head.rstrip() + "。"
            # **备好的一个都不能直接发时，不给 `/job-outcome`。**
            #
            # `_ready_text` 在 `ready_strong == 0` 时说的是「**别当群发名单**」
            # —— 而这里原来无条件交出 `/job-outcome <公司>`，那是「记一笔已投递」。
            # 同一句话前半句叫他别发、后半句叫他记一笔投递，**自相矛盾**，
            # 而且错的那一半踩的是全局安全铁律：记一笔 = 替用户认定「投出去了」，
            # 它写进 `job_search_tracker.csv`，往后回复率、漏斗、面试/offer
            # 三条分支全从这行记录长出来。`workflows/job-auto.md`
            # 「什么归机器，什么永远归人」那张表的判据是
            # 「**后果是不是只有用户承担**」——**记一笔正好是他承担**。
            #
            # 「有材料没发 → 先发」那条裁定（2026-08-29）的前提是备好的那些
            # **发得出去**；一个都发不出去时，那个前提不成立。
            #
            # 该给的是补齐那一档缺的东西：`04` 规定「投前必问」写不出来
            # 就说明它不属于这一档（`job-apply.md` 的补法表原话），所以
            # `/job-apply 可以考虑` 逼着每个岗自己结一次案，而不是替他记一笔假的。
            _rs = counts.get("ready_strong")
            _ra = counts.get("ready_asked")
            _maybe = left if _rs == 0 else None
            if _maybe is not None and isinstance(_ra, int) and _ra >= _maybe:
                # 都列了要问什么 → 没有什么可敲的了，人就在页面上，自己看。
                # 命令留空是诚实的：这一页没有第二条命令可给。
                return (_head + _season, "")
            if _maybe is not None:
                return (_head + _season, "/job-apply 可以考虑")
            return (_head + _season, "/job-outcome <公司>")
        # 手上的都发完了 —— 下一步是补货，不是催。
        #
        # 这里原来是「都投出去了，等回复。超过 N 天没动静的可以催一次」，
        # 命令给的是 `/job-outcome followup`。2026-08-29 按用户裁定改掉
        # （见下面那段，正本在 `AGENTS.md`「跟进归用户，工具不催」）。
        # 顺带解掉的还有一条老毛病：**「等」不是下一步**（`AGENTS.md`
        # 「每一处引导都要写出该敲的命令」里点名的那条）——「等回复」
        # 那半句他动不了手，而现在这一句是他敲得动的。
        return ("可以投的都发出去了，手上没有待处理的。接着抓下一批",
                "/job-auto")
    if counts["materials"] > 0:
        # 曾经写「投出后勾「已发」」——那个勾选框**只存在于单页版**
        # （build_dashboard 自己渲染的 `<input class="sent-toggle">`），网页版没有。
        # 而这句话由两个面板共用，于是网页版用户会去找一个不存在的控件。
        # 共用的文案里不许出现任一边独有的控件名。
        # 说「复制开场白」不说「复制话术」：屏幕上那个按钮就叫「复制开场白」。
        # 一个动作从被指路到被按下，得用同一个名字。
        return ("材料就绪，去投递：复制开场白、开职位链接投出去。投完回来记一笔",
                "/job-outcome <公司>")

    # 有材料却不在 seen_jobs 里（手动找到的岗直接跑了 /job-apply）——这些目录是真实存在的
    # 产出，只是面板匹配不上，不能只说「还没抓职位」把它们晾在一边。
    stray = list(unmatched_apps or [])
    if stray:
        return (f"这些投递目录已有材料，但对应职位不在 seen_jobs 里，未上面板："
                f"{'、'.join(stray)}。投了就跑 /job-outcome 记一笔；想让它们上面板，"
                f"下轮 /job-scrape 收录到即可", "/job-outcome <公司>")

    if top_ranked_url:
        # **给批量入口，不给单岗链接。**
        #
        # 原来这里是 `f"/job-apply {top_ranked_url}"` ——「排好了，给头部岗生成材料」。
        # 那个理由是「排序结果写在机器读的文件里，人能看的只有总览页，所以他得先
        # 去挑一个」（`doctor` 同一支的注释原话）。**它对单岗成立，对这一支不成立**：
        # 这一支的条件是「有可投的已评岗没材料」，而**用户不知道该做什么时问的正是
        # 「我手上还有什么没做完的」**，答案是一批，不是那一个。
        #
        # 后果不是多敲一次：面板叫他一个一个敲，而他之所以在敲第 3 个，
        # 恰恰是因为他不知道有批量那条路。`job-apply.md`「按档批量」那一节
        # （`全部` = 「除了不投的都准备好」）就是为这句话准备的。
        #
        # `top_ranked_url` 现在只当**条件**用（有没有可投的已评岗），不再当答案 ——
        # 它在 `export_web_data` 里算出来时就已经是「可投」那三档里最高分的一个了。
        return ("排好了，把可投的批量出材料", "/job-apply 全部")

    # 到这里：没有可投的已评岗。区分「还没评」与「评完了但没一个能投」。
    if isinstance(n_unranked, int) and n_unranked > 0:
        return (f"还有 {n_unranked} 个抓到但没评的职位：跑 /job-rank 批量打分", "/job-rank")
    if counts["ranked"] > 0:
        return ("已评的职位没有一个通过筛选（硬性条件没过，或者分太低）——先去找更多岗，"
                "或者回头调整 profile 里的硬性条件与期望", "/job-scrape")
    if counts["scraped"] == 0:
        # 脊梁那条，不是它的分解 —— 判据同 `doctor.next_step` 里那一支
        #（`AGENTS.md`「一次跑到头：只有三条命令」，以及紧跟着那句
        # 「别把这条脊梁说成四步」）。
        return ("还没抓职位：跑 /job-auto 抓岗评分出材料，中途不用盯着", "/job-auto")
    return ("抓到了但还没排名：跑 /job-rank 批量打分", "/job-rank")


def load_seen_jobs(path: Path) -> dict:
    """Load the scraper state. Exit with guidance when absent/empty."""
    if not path.is_file():
        raise SystemExit(_cli.no_store(path))
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"seen_jobs.json 解析失败（{exc}）—— 文件可能损坏，可重新运行 /job-scrape 重建")
    # **两代格式都要认**：真实结构是 `{"seen": {…}}`，早期库顶层直接就是
    # `{key: {…}}`。正本是 `_cli.seen_of`。写成 `.get("seen") or {}` 的后果是
    # 老库上直接报「里面没有职位」——比静默归零响，但同样是错的
    # （`doctor.py` 那处是静默版，2026-08-21 同日修的）。
    seen = _cli.seen_of(data)
    if not seen:
        raise SystemExit("seen_jobs.json 里没有职位 —— 请先运行 /job-scrape 抓取职位")
    return seen


def _section(text: str, keyword: str) -> str:
    """标题里**含** keyword 的那一节的正文，到下一个 `## ` 为止。

    关键词可以出现在标题的任何位置，不必紧跟 `## `。apply.md 自己就规定了
    「渠道 N：」这种编号前缀（见其「### 渠道 4：求职信」），所以 AI 产出
    `## 渠道 1：打招呼开场白（…）` 和 `## 打招呼开场白（…）` 都合法。
    原来要求关键词紧跟 `## `，于是带编号前缀的那种整篇解析为空 —— 面板上
    「三渠道话术」点开什么都没有。实测 4 个真实投递目录里 1 个中招，
    而它恰好是分最高、材料最全的那个岗。
    """
    # **`##+` 不是 `##`。** 这里原来两处都写死两个井号，于是 `### 结论：…` 这种
    # 三级标题整节读不出来 —— 而 `04-job-evaluation.md` 的输出格式里，结论那一节
    # 用的正是 `### 结论：`。同一个文件里判词那条锚点正则早就写成 `^##+\s*结论`，
    # 只有这里没跟上。
    #
    # 后果不是「读不出」，是**读错**：`parse_evaluation` 的兜底写着
    # `_section(text, "结论") or text` —— 这一节读不出就退回**扫全文**，
    # 而全文里最早出现的那个档位词可能是任何一句解释。
    #
    # 实测（2026-08-26）：一份 80 分、结论写着「值得投」的评估，头部有一行
    # 「`behavioral.md` 未填，本轮**跳过**语气/文化匹配校准」——判词被读成
    # 「跳过」，`writeback` 照着把职位库改成了「跳过」。那个岗当时是分最高的一个，
    # 而「跳过」在面板上会把它扔进「不投的岗位」。**误报向下比向上更难发现**：
    # 向上会被用户投一次戳穿，向下是这个岗从此不再出现在他眼前。
    m = re.search(
        rf"^##+\s+[^\n]*?{re.escape(keyword)}[^\n]*\n(.*?)(?=^##+ |\Z)",
        text,
        re.S | re.M,
    )
    return m.group(1).strip() if m else ""


def _strip_tail_meta(x: str) -> str:
    """反复剥尾部元数据：字数行、操作备注、HTML 注释、分隔线。

    开场白与邮件正文共用这一份——两处各写一遍必然飘，而这两处剥的
    正是同一批尾巴（字数校验、`---`、写给你自己看的附件备注）。
    """
    prev = None
    while prev != x:
        prev = x
        # 「字数」前面可能还带别的字（真实产出里有「（正文字数：397，含署名…）」），
        # 所以不能锚死在括号开头。
        x = re.sub(r"（[^）]*字数[：:][^）]*）\s*$", "", x)      # （字数：199）
        x = re.sub(r"（[^）]*\*\*[^）]*\d+\s*字\*\*[^）]*）\s*$", "", x)  # （正文 **约 390 字**…）
        # 尾部的**操作备注**：写给你看的，不是要发给对方的。真实产出里有
        # 「**附件命名**：某某-某某岗-简历.pdf」「⚠️ **附件改名**：落盘的文件叫 resume.pdf…」
        # 「**收件人留空**：…」——它们跟在署名之后、自成一段，而这段正文是
        # 用户**整段粘进邮件**发给对方的。6 份真实邮件里 3 份带着这种尾巴。
        # 判据要窄：必须是**独立一段**、以可选的警告号开头、随后是一个短加粗
        # 标签加冒号。正文里的加粗（「**租户权限…我没有做过**，」）不在段首，
        # 也不带冒号，碰不到。
        # 警告号要写成 `+`：`⚠️` 是**两个码位**（U+26A0 加变体选择符 U+FE0F），
        # 字符类一次只吃一个，写成 `?` 时它只吃掉前半个，后半个顶在 `**` 前面
        # 匹配就断了——实测那一条备注因此没被剥掉，而它下面那条被剥了。
        x = re.sub(r"(?s)\n\s*\n(?:[⚠️⚠]+\s*)?\*\*[^*\n]{1,14}\*\*[：:].*$", "", x)
        # 尾部那行**引用体的字数自检**（`> 字数校验：约 385 字，≤400 ✓`）。
        # 按它**说了什么**认，不按「是不是引用行」认：后者会把整段引用的
        # 正文一行行吃光（下面 `_strip_wordcount` 那段注释记着这个坑）。
        x = re.sub(r"\n\s*>[^\n]*(?:字数|字符数|校验)[^\n]*$", "", x)
        # 尾部 HTML 注释。**必须挡住跨注释匹配**：`<!--.*?-->` 的非贪婪只是
        # 「找最近的 -->」，配上 `$` 锚点后，匹配从**第一个** `<!--` 一直吞到
        # 结尾——「开头提示注释 + 正文 + 尾部自检注释」这种两头都有注释的
        # 开场白会被整段吃成空串（实测），而空串在面板上表现为「话术是空的」，
        # 比带标记更难发现。tempered dot：中途再遇到 `<!--` 就不许继续。
        x = re.sub(r"(?s)<!--(?:(?!<!--).)*?-->\s*$", "", x)
        x = re.sub(r"\n?\s*(?:---+|\*\*\*+)\s*$", "", x)     # 尾部分隔线
        x = x.strip()
    return x


def _strip_wordcount(s: str) -> str:
    """剥掉话术尾部的**元数据**，只留要发出去的正文。

    开场白是直接粘进聊天框发给 HR 的，混进任何一行说明都会被一起发出去。
    真实产出里出现过这几种尾巴，都必须剥：

      （字数：199）
      （正文字数：397，含署名、不含主题与附件名）
      > 字数校验：**192 字**（去空白字符计），≤200 ✓；第一句即为最硬匹配点 ✓
      **附件命名**：某某-某某岗-简历.pdf        ← 写给你自己看的，不是给对方的
      ---

    剥的动作在模块级的 `_strip_tail_meta` 里，与 `_clean_email_body` 共用一份。

    只从**尾部**反复剥，不动正文中间的内容（万一正文里真有引用行）。
    """
    # 三段，顺序不能换。
    #
    # **① 先剥掉尾部的非引用元数据**（字数行、分隔线、HTML 注释）。
    # **② 再看剩下的是不是整段引用块**，是就把行首 `> ` 剥掉。
    # **③ 最后才剥尾部的引用行**（那是自检备注，形如 `> 字数校验：…`）。
    #
    # ① 必须在 ② 之前：真实文件里引用块后面跟着一行 `（**168 字**…）`，
    # 有它在，「整段都是引用」判不成立，② 就不会触发。
    # ③ 必须在 ② 之后：③ 会**反复**剥尾部引用行，整段都是引用时它会一行一行
    # 把正文全吃光，返回空串——实测就是这样（`test_outreach_parsing` 报
    # 「开场白解析成空」）。而空串在面板上表现为「话术是空的」，比带标记更难发现。
    #
    # 为什么非剥不可：开场白是**直接粘进聊天框**的，`> ` 会原样跟着粘过去，
    # HR 收到一段每行带尖括号的话。面板上的复制按钮取的就是这里的返回值。
    # 实现在模块级的 `_strip_tail_meta`——邮件正文要用同一份。

    s = _strip_tail_meta(s)
    # 开头的 HTML 注释（给写文件的人看的提示）同样不能进正文
    s = re.sub(r"(?s)^\s*<!--.*?-->\s*", "", s).strip()

    # 只在**整段都是引用行**时剥（空行不算），避免动正文中间偶然出现的一行引用
    # ——比如引 JD 原话那种，剥掉会让引用失去边界。
    lines = s.split("\n")
    body = [ln for ln in lines if ln.strip()]
    if body and all(ln.lstrip().startswith(">") for ln in body):
        s = "\n".join(re.sub(r"^\s*>\s?", "", ln) for ln in lines).strip()

    prev = None
    while prev != s:
        prev = s
        s = _strip_tail_meta(s)
        # **换行不是可选的。** 这里要剥的是「最后**一整行**是引用」（自检备注长那样），
        # 而那个 `?` 让它退化成「最后一行里**任意位置**的尖括号到行尾」——于是
        # `转化率 3% > 行业均值 1.8%。` 会被削成 `转化率 3%`，一句话从中间断掉。
        # 而这段字是**直接粘进聊天框发给 HR 的**，断句会原样发出去。
        # 实测活动用户 2026-08-23：245 个要发出去的小节里只有 1 个含尖括号，今天没踩到；
        # 但开场白是大模型现写的自由文本，「A > B」这种比较写法随时会出现。
        # 判据见 `tests/test_a_greater_than_is_not_a_quote_line.py`。
        #
        # 去掉 `?` 不会漏掉「整段都是引用」那种：那一支在上面第 ② 步已经处理过
        # （整段引用先被剥成正文），到这里不可能还剩一个行首引用。
        s = re.sub(r"\n\s*>[^\n]*$", "", s)             # 尾部引用行（自检备注）
        s = s.strip()
    return s


def _strip_body_label(s: str) -> str:
    """剥掉正文开头的「**正文：**」标签行 —— 它是排版标记，不是要发出去的内容。"""
    return re.sub(r"^\*\*正文[：:]?\*\*[：:]?\s*", "", s.strip()).strip()


def _clean_email_body(s: str) -> str:
    """邮件正文：剥到只剩要发出去的字。

    **不能直接套 `_strip_wordcount`。** 那个函数最后一段会**逐行**剥尾部的引用行
    （开场白的自检备注长那样），而邮件正文常常是整段 `> ` 引用块——一旦这一节的
    开头还有「**主题行**」和一段围栏（真实产出里就有），「整段都是引用」判不成立，
    于是那一步从后往前一行一行把正文吃光，只剩标题。实测就是这样。

    所以邮件走自己这一串：剥围栏 → 剥「**正文**」标签 → 剥尾部元数据 →
    整段都是引用就去掉行首前缀。**唯独不做**「逐行剥尾部引用」那一步。
    """
    # **先剥围栏、再剥标签。** 主题那段代码围栏的收尾留在正文开头，
    # 标签「**正文**」排在它后面——反过来剥的话，标签前面顶着三个反引号，
    # 锚在行首的那条规则匹配不上，于是「**正文**」原样进了要发出去的邮件。
    s = re.sub(r"^```[^\n]*\n?", "", s.strip())
    s = re.sub(r"\n```\s*$", "", s).strip()
    s = _strip_body_label(s)
    s = _strip_tail_meta(s)
    lines = s.split("\n")
    body = [ln for ln in lines if ln.strip()]
    if body and all(ln.lstrip().startswith(">") for ln in body):
        s = "\n".join(re.sub(r"^\s*>\s?", "", ln) for ln in lines).strip()
    return s.strip()


def parse_outreach(text: str) -> dict:
    # 冒号全角半角都认——标签是 AI 写的，两种都真实出现过。
    url_m = _cli.LINK_LINE.search(text)
    email_sec = _section(text, "邮件")
    # 四种写法都要认，真实产出里都出现过：
    #   `**主题**：xxx`、`**主题：** xxx`（冒号在加粗内）、
    #   `**主题行**` 后面另起一行、以及主题被放进一段代码围栏里。
    # 少认一种的代价不是「没主题」而已：认不出来时整段（含「**主题行**」和围栏）
    # 都会当成正文，用户复制走的邮件里带着一行标题和三个反引号。
    subj_m = re.search(
        r"\*\*主题(?:行)?[：:]?\*\*[：:]?[ \t]*(?:\n+```[^\n]*\n)?[ \t]*(.+)",
        email_sec)
    return {
        "url": url_m.group(1) if url_m else "",
        "greeting": _strip_wordcount(_section(text, "打招呼开场白")),
        "email_subject": subj_m.group(1).strip() if subj_m else "",
        # **邮件正文和开场白一样要剥元数据。** 原来只剥了「**正文：**」那个标签，
        # 于是字数校验行、`> ` 引用前缀、尾部的「附件改名 / 收件人留空」备注
        # 全留在正文里——而这段字是用户整段粘进邮件发给用人方的。
        # 开场白那一侧从一开始就走 `_strip_wordcount`，邮件这一侧漏了。
        "email_body": _clean_email_body(
            email_sec[subj_m.end():] if subj_m else email_sec),
        "wangshen": _strip_wordcount(_section(text, "网申自评")),
        # 抬头那一块（第一个 `## ` 之前）。**「在跟谁说话」那半句写在这儿**，
        # 而它决定第二轮怎么说话（猎头问薪资直接答，直招不主动展开）。
        # 判据在 `_cli.addressee_problem`，消费方是导出侧那条 `addresseeWarn`。
        "head": _cli.head_of(text),
        # 「本次使用的公司事实」那一节列了哪几条。**空的不等于漏了**
        # —— 只有开场白真对公司下了断言时才算问题，判据在
        # `_cli.claim_without_source`（与审计同一份）。
        "facts": _cli.fact_items(text),
    }


