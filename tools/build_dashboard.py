def spring_festival(year: int):
    """那一年的春节是哪天。**表里没有就返回 None**，不外推。"""
    md = SPRING_FESTIVAL.get(year)
    return _dt.date(year, *md) if md else None


#: 国庆黄金周：**公历固定 10 月 1–7 日**，不用查表（春节要表是因为它是农历的）。
#:
#: 它和春节那个坎是两件事，别合并：
#:
#:     春节   三四周的冻结，**压过**月份表 —— 那段时间「现在是淡季」这句话
#:            既太轻也太晚，他要知道的是「没回音不怪你的材料」。
#:     国庆   七天的暂停，落在「金九银十」的**正中间**。十月是旺季没错，
#:            但头一周没人上班 —— 所以它是**补一句**，不是改结论。
#:
#: 全仓搜过（2026-08-24）：`国庆` / `黄金周` / `长假` 全是 0 命中。
NATIONAL_DAY_BEFORE = 5
NATIONAL_DAY_LAST = 7
NATIONAL_DAY_AFTER = 14


def national_day_phase(today):
    """国庆假期这一档 → 一句补充，不在这个窗口里就 None。

    **只补一句，不改结论。** 十月本来就是旺季，这七天不改变「该投」这件事，
    只改变「这几天发出去什么时候有人看」和「这几天的沉默算不算数」。
    """
    y = today.year
    start = _dt.date(y, 10, 1)
    end = _dt.date(y, 10, NATIONAL_DAY_LAST)
    if start - _dt.timedelta(days=NATIONAL_DAY_BEFORE) <= today <= end:
        return ("假期",
                "不过 10 月 1–7 日是国庆假期：这几天发出去的要等节后才有人看，"
                "别按这几天的沉默下结论")
    if end < today <= _dt.date(y, 10, NATIONAL_DAY_AFTER):
        return ("刚回来",
                "不过国庆刚过：假期里积压的简历这一周一起被翻，"
                "回得比平时慢一点是正常的，先别急着改材料")
    return None


def spring_festival_phase(today):
    """现在是不是卡在春节那个坎上 → (档位, 说给用户的话)，不是就 None。

    三档，因为它们对「下一步做什么」的含义完全不同：

        冻结    节前两周 ~ 节后开工。投了也多半没人看 ——
                这一档最要紧的作用是**别让他把没回音当成简历的问题**。
        刚开工  开工 ~ 元宵。人回来了但还在收拾，是个爬坡。
        （其余） 不说。

    **年份不在表里就一句都不说**，和 `hiring_calendar` 认不出求职状态时同一个
    处理：说错季节比不说更坏。
    """
    cny = spring_festival(today.year)
    if cny is None:
        return None
    gap = (today - cny).days
    if -FREEZE_BEFORE <= gap <= FREEZE_AFTER:
        return ("冻结",
                f"这几周是春节前后（今年正月初一是 {cny.month} 月 {cny.day} 日）："
                f"HR 大量休假、面试排不上、审批也停着。"
                f"这段时间投出去没回音说明不了你材料的事，别据此改简历。"
                f"节后开工那两周人一起回来，是全年最好的窗口之一——现在把料备齐")
    if FREEZE_AFTER < gap <= LANTERN_AFTER:
        return ("刚开工",
                f"刚过春节，人陆续回岗但还在收拾（元宵之后才算完全恢复）。"
                f"现在投是对的时候——比节前那两周强得多，"
                f"但头几天回得慢，别急着下结论")
    return None


def hiring_calendar(stage: str | None):
    """按他在职业的哪一段挑日历。**认不出来就返回 None** —— 不猜。

    认不出时上层一句季节的话都不说：说错季节比不说更坏 ——
    它会让人在该动的时候按兵不动，或者在真淡季白投一轮。
    """
    s = (stage or "").strip()
    if not s:
        return None
    if any(w in s for w in CAMPUS_WORDS):
        return CAMPUS_SEASON
    return HIRING_SEASON


