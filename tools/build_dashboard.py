def n_parked(seen: dict) -> int:
    """降权泊车的数量：还在待评里，但只有标题这一层依据显示方向不对。

    它们**没有结案**——标题判不了死刑（见 `prescreen.py` 的规则分组说明）。
    但也不该和真正待办的混在一个数里：抓 JD 的额度有限，先花在没被降权的上面。
    分开计数就是当初那个「队列排不空」的记账问题的正解——用记账解决，不用判词。
    """
    return sum(1 for e in seen.values()
               if (e.get("status") or "") == "new" and e.get("deprioritized"))




def resolve_score(entry: dict, app) -> tuple:
    """返回 (分数, 判词, 是否深评过)。**有 evaluation.md 就以它为准。**

    `/job-rank` 的粗筛分只读职位文本，不做公司调研、不做能力边界比对；`/job-apply` 的深评分
    两样都做了。实测同一个岗粗筛 76「强匹配」、深评 62「值得投」——14 分的落差，
    而落差正好来自粗筛没做业务领域匹配。

    `apply.md` 要求把深评分写回 `seen_jobs`，但**光靠流程指令不够**：AI 漏一步，
    用户就又看到虚高的分。所以这里再兜一道——两道保险任一生效都能得到正确结果。
    """
    ev = (app or {}).get("evaluation") or {}
    score, verdict = ev.get("score"), (ev.get("verdict") or "").strip()
    # **判「有没有」，不判「真不真」。** 原来是 `if score or verdict`，
    # 于是深评给 0 分、判词又恰好没解析出来时整个分支被跳过，面板回退去显示
    # 粗筛的高分——正好绕开这个函数存在的理由。
    # 真实数据里暂时没有 0 分深评（2026-08-20 查过 284 个材料目录），
    # 但 0 是合法分数，而这一步的代价是把虚高的分端给用户。
    has_score = score is not None and str(score).strip() != ""
    if has_score or verdict:
        try:
            n = int(str(score).strip()) if str(score).strip() else None
        except ValueError:
            n = None
        # 深评结论不带「粗筛：」前缀
        v = _cli.strip_triage(verdict)
        # `parse_evaluation` 只认得出「硬门 FAIL」四个字（门名要 parse_gates，
        # 在导出器里）。库里存的是带门名的完整写法，两者同为硬门 FAIL 时
        # 取信息更全的那个，免得面板上「不满足硬性条件」后面缺了是哪一条没过。
        #
        # **两种存法都要认。** 库里的硬门写法有两代：老的 `硬门 FAIL (学历院校)`
        # （485 条存量）和新词表 `不满足硬性条件（专业）`（2026-08-13 起）。
        # 这里原来只认老写法——2026-08-14 按裁定翻案 9 个岗（评估、库都写了
        # 带门名的新写法）之后，面板显示的却是光秃秃的「硬门 FAIL」：门名丢了，
        # 还把内部英文码端给了用户。
        stored = entry.get("rank_verdict") or ""
        if v == "硬门 FAIL" and stored.startswith(("硬门 FAIL (", "不满足硬性条件")):
            v = stored
        return n, v, True
    # **库里那个分也要过同一道转换。** 上面深评那一支早就 `try/except` 转成
    # `int` 了（分数是人和 AI 都写的，写成字符串是常事），而这条兜底路径
    # 一直把原值直接递出去 —— 实测 2026-09-01：库里一个 `"七十"`，导出器在
    # `jobs.sort(key=... -(j["score"] or 0))` 上 `TypeError`，**整个面板出不来**。
    #
    # 转不动就当没分（`None`）：面板上它显示成「还没评分」，看得见；
    # 而不是让一个岗把整页数据带走。判据与上面那一支同一条，不另立。
    # ⚠️ **判 `is None`，别用 `or`。** 写成 `str(raw or "")` 的话 `0` 被
    # 当成空 —— 而 0 是合法分数，这个函数上面那一支为同一件事记过一课
    #（「原来是 `if score or verdict`，于是深评给 0 分时整个分支被跳过」）。
    # 我自己第一版就踩回去了，测试当场红。
    raw = entry.get("rank_score")
    txt = "" if raw is None else str(raw).strip()
    try:
        n2 = int(txt) if txt else None
    except ValueError:
        n2 = None
    return n2, (entry.get("rank_verdict") or ""), bool(entry.get("evaluated"))








#: 命令分组：跟着流程走，不按字母序。键是 workflow 名（= 文件名去掉 .md）。
#:
#: 分组本身是**给用户看的编排**，不是数据——所以写在这里而不是塞进 AGENTS.md
#: 那张表（那张表是给 AI 工具用的索引，加一列展示用的分组会污染它）。
#: 但**成员资格必须完整**：漏掉一个，它就掉进「其它」里失去上下文。
#: `tests/test_command_reference.py` 会检查 `workflows/*.md` 全部落在某个组里。
#: 名字取自 `workflows/INDEX.md` 索引里的 `workflows/<名>.md`，所以带 job- 前缀。
#: 漏一个不会报错，只会被归进「其它」——`test_command_reference` 盯着这件事。
COMMAND_GROUPS = [
    ("开始之前", ["job-setup", "job-user"]),
    ("找岗、挑岗", ["job-scrape", "job-rank", "job-auto", "job-expand",
                "job-add-portal"]),
    ("投一个岗", ["job-resume", "job-refresh", "job-apply", "job-cv",
              "job-add-template"]),
    ("投出去之后", ["job-outcome", "job-interview", "job-offer", "job-upskill"]),
    ("看数据、同步", ["job-dashboard", "job-html-report", "job-gmail-sync",
                 "job-notion-sync"]),
    ("其它", ["job-reset"]),
]


def _md_plain(x: str) -> str:
    """索引表里的 markdown 记号 → 纯文本。面板那几格不是 markdown。

    `workflows/INDEX.md` 的索引表本身是 markdown，`**所有**` 在那里是对的；而面板把这几格
    当纯文本节点渲染，星号会原样上屏。同一份内容两种载体，转换点就在读进来这一下。
    """
    return re.sub(r"\*\*([^*\n]+)\*\*", r"\1", x).replace("`", "").strip()


def parse_commands() -> list[dict]:
    """从 `workflows/INDEX.md` 的「工作流索引」表里读出全部命令。

    **不在前端写死这张表。** 写死必然跟索引飘：加一个工作流、改一句说明，
    面板还停在上一版，而用户没有任何理由怀疑面板漏了东西。索引是权威来源
    （正本就在 `workflows/INDEX.md`，`AGENTS.md` 那一节只剩指向这里的指针），
    这里只做展示层的分组。

    表长这样：

        | 任务 | 正文 | 怎么敲（举例） | 不给参数时 |
        | 深评一个岗：… | `workflows/job-apply.md` | `/job-apply <职位链接…>` · … | 可以投的全部备料，不限量 |

    第三列按 ` · ` 分成多条举例，**每条都留着**（原来只取第一个斜杠命令，其余
    直接丢掉——而那一列本来就叫「示例」，丢掉的正是用户最需要的东西：这个命令
    还能怎么敲）。第一条是标准形式，`cmd` 从它取（连同 `<参数>` 提示）；
    括号里的补充说明跟着各自那条走，不拆开。

    **第四列「不给参数时」是可选的**，缺了就是空串。它回答的是用户敲下裸命令
    之前最想知道的那件事——「我什么都不填，它会干什么」。这问题原来只有读
    `workflows/<名>.md` 才有答案，而那正是面板存在的意义要消灭的动作。
    （2026-08-13 用户要求：「命令说明里提供供新手简单使用的命令和具体的
    每个命令的说明，适合后期进阶」——脊梁那几条给新手，这一列给进阶。）
    （脊梁是几条以 `AGENTS.md`「一次跑到头」为准，此刻三条：setup / auto / outcome。）
    """
    src = REPO_ROOT / "workflows" / "INDEX.md"
    if not src.is_file():
        return []
    text = src.read_text(encoding="utf-8", errors="replace")
    # 锚到「工作流索引」这一节，别把文件开头那段「谁是正本」的引言也吃进来
    m = re.search(r"^##\s*工作流索引\s*$(.*?)(?=^##\s|\Z)", text, re.S | re.M)
    if not m:
        return []

    by_name: dict[str, dict] = {}
    for ln in m.group(1).splitlines():
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[1].startswith("---"):
            continue
        wf = re.search(r"workflows/([\w-]+)\.md", cells[1])
        cmd = re.search(r"(/[a-z-]+)((?:\s*<[^>]+>)?)", cells[2])
        if not wf or not cmd:
            continue
        # 反引号和星号都是 markdown 的记号，不是要显示的内容。反引号早就剥了
        # （留着用户照抄命令会多敲两个字符）；**星号一直没剥**——面板上因此印着
        # 「拿你投过的**所有**岗一起算」，四个星号原样上屏。索引表是 markdown，
        # 而面板这一格是纯文本节点，两边的规矩不一样，进来时就得换掉。
        examples = [_md_plain(e) for e in cells[2].split("·") if e.strip()]
        by_name[wf.group(1)] = {
            "name": wf.group(1),
            "cmd": (cmd.group(1) + cmd.group(2)).strip(),
            "does": _md_plain(cells[0]),
            "examples": examples,
            # 第四列可选：老表只有三列时不该炸，也不该凭空编一个默认行为出来
            "bare": (_md_plain(cells[3]) if len(cells) > 3 else ""),
        }

    out, placed = [], set()
    for title, names in COMMAND_GROUPS:
        items = [by_name[n] for n in names if n in by_name]
        placed.update(i["name"] for i in items)
        if items:
            out.append({"group": title, "items": items})
    # 没归组的**不能丢**——丢了用户就永远看不到它。放进「其它」，
    # 测试会因为它出现在那里而变红，逼人回来给它一个位置。
    rest = [v for k, v in by_name.items() if k not in placed]
    if rest:
        other = next((g for g in out if g["group"] == "其它"), None)
        if other:
            other["items"] += rest
        else:
            out.append({"group": "其它", "items": rest})
    return out


























