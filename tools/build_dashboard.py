#: 占位符那条正则原来**在这里也编译了一份**（`_PLACEHOLDER_RE`），与
#: `doctor._PLACEHOLDER` 同值而不同名 —— 按名字找副本的守卫看不见它，
#: 按值找副本的那条（`test_one_value_one_home`）当时还不看 `re.compile`。
#: 2026-08-31 归到 `doctor.placeholders`，代价写在那个函数的 docstring 里。


def profile_ready(candidate_path: Path) -> bool:
    """资料填完了没有——判据是**模板里的占位符还剩几个**，不是「有没有 `[YOUR_`」。

    原来写的就是 `"[YOUR_" not in text`。可 `profile.example/candidate.md` 里 74 种
    占位符，这条只看得见 38 种：`[DEGREE]`（学历）、`[COMPANY_TYPE]`、
    `[DISQUALIFYING_KEYWORDS]`（排除关键词）、`[FORBIDDEN_CLAIM_1]`（能力边界禁区）
    这一大类都不以 `YOUR_` 开头。**实测**把模板里 `[YOUR_*]` 那一半填上、其余原样
    留着，这道门判「已就绪」——而那份资料还剩 36 个占位符，学历和能力边界禁区全是
    模板。面板于是接着建议去抓职位、去投递，`/job-apply` 拿这份资料去核对「有没有越过
    能力边界」，对照的是 `[FORBIDDEN_CLAIM_1]`。

    占位符清单**现从模板抽**（`doctor.template_tokens`），不在这里另抄一份——抄一份
    的下场是模板加了新占位符、检查还认着旧的。取交集而不是直接扫 `[A-Z_]+`：用户
    自己写的 `[TODO]`、`[API]` 不该被当成没填完。

    模板取不到时（`profile.example/` 被删、doctor 被改坏）退回原来那条窄判据：
    那时无从判断，既不放宽也不收紧，保持既有行为。
    """
    if not candidate_path.is_file():
        return False
    try:
        text = candidate_path.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        print(f"警告: {candidate_path} 不是 UTF-8（{exc.reason}），无法判断资料是否就绪；"
              f"请把它另存为 UTF-8", file=sys.stderr)
        return False
    tokens = _template_tokens("candidate.md") if _template_tokens else set()
    if not tokens:
        return "[YOUR_" not in text
    return not (tokens & _placeholders(text))


